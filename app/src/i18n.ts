export const STRINGS: Record<Lang, Strings> = { ca, es, en };
export type StringKey = keyof Strings;

export const LANG_LABEL: Record<Lang, string> = { ca: 'Català', es: 'Castellano', en: 'English' };

/** Phone in Catalan -> Catalan; in Spanish -> Spanish; anything else -> English. */
export function deviceLanguage(): Lang {
  try {
    for (const locale of getLocales()) {
      const code = locale.languageCode?.toLowerCase();
      if (code === 'ca' || code === 'es' || code === 'en') return code;
    }
  } catch {
    // fall through
  }
  return 'en';
}

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? STRINGS.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const LOCALE: Record<Lang, string> = { ca: 'ca-ES', es: 'es-ES', en: 'en-GB' };

export function money(amount: number, lang: Lang): string {
  try {
    return new Intl.NumberFormat(LOCALE[lang], { style: 'currency', currency: 'EUR' }).format(amount);
  } catch {
    return `${amount.toFixed(2).replace('.', lang === 'en' ? '.' : ',')} €`;
  }
}

export function km(distance: number, lang: Lang): string {
  if (distance < 1) return `${Math.round(distance * 1000)} m`;
  return `${distance.toFixed(1).replace('.', lang === 'en' ? '.' : ',')} km`;
}
